#!/usr/bin/env node
/**
 * Generates docs/diagrams/dependencies.md from docs/dependency-graph.json
 * (the same normative source enforced by check-dependency-graph.mjs).
 *
 *   node infra/scripts/generate-dependency-diagram.mjs          # write
 *   node infra/scripts/generate-dependency-diagram.mjs --check  # CI drift gate
 *
 * Built/planned status is derived from the filesystem: a package counts as
 * built when its directory exists AND its package.json name matches the node.
 * Output is byte-deterministic (json key insertion order is stable).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const graphPath = join(root, 'docs', 'dependency-graph.json');
const outPath = join(root, 'docs', 'diagrams', 'dependencies.md');
const checkMode = process.argv.includes('--check');

const graph = JSON.parse(readFileSync(graphPath, 'utf8'));

/** @aca/web|api|worker(-plugins) live under apps/, the rest under packages/. */
function dirFor(name) {
  const short = name.replace('@aca/', '');
  const app = join(root, 'apps', short);
  const pkg = join(root, 'packages', short);
  return { app, pkg };
}

function isBuilt(name) {
  const { app, pkg } = dirFor(name);
  for (const dir of [app, pkg]) {
    const manifest = join(dir, 'package.json');
    if (!existsSync(manifest)) continue;
    try {
      if (JSON.parse(readFileSync(manifest, 'utf8')).name === name) return true;
    } catch {
      /* unreadable manifest => not built */
    }
  }
  return false;
}

const nodeId = (name) => name.replace('@aca/', '').replaceAll('-', '_');
const devOnly = new Set(graph.devOnlyTooling ?? []);
const prodLayers = Object.entries(graph.layers).filter(([n]) => !devOnly.has(n));
const maxLayer = Math.max(...prodLayers.map(([, l]) => l));

const lines = [];
lines.push(`flowchart BT`);
lines.push(`  classDef built fill:#d3f9d8,stroke:#2b8a3e,color:#000`);
lines.push(`  classDef planned fill:#fff3bf,stroke:#e8a100,color:#000,stroke-dasharray:5 5`);

for (let layer = 0; layer <= maxLayer; layer += 1) {
  const names = prodLayers.filter(([, l]) => l === layer).map(([n]) => n);
  if (names.length === 0) continue;
  lines.push(`  subgraph L${layer}["Layer ${layer}"]`);
  for (const name of names) {
    const dirName = name.replace('@aca/', '');
    const home = existsSync(dirFor(name).app) ? `apps/${dirName}` : `packages/${dirName}`;
    lines.push(`    ${nodeId(name)}["${name}<br/>${home}"]`);
  }
  lines.push(`  end`);
}

const edgeSet = new Set();
for (const [from, deps] of Object.entries(graph.edges)) {
  if (devOnly.has(from)) continue;
  for (const to of deps) {
    if (devOnly.has(to)) continue;
    edgeSet.add(`${nodeId(from)} --> ${nodeId(to)}`);
  }
}
for (const e of [...edgeSet].sort()) lines.push(`  ${e}`);

const plannedSet = new Set();
for (const [from, deps] of Object.entries(graph.plannedEdges ?? {})) {
  for (const to of deps) {
    const key = `${from}→${to}`;
    if ((graph.edges[from] ?? []).includes(to)) continue;
    plannedSet.add(`${nodeId(from)} -.planned.-> ${nodeId(to)} %% ${key}`);
  }
}
for (const e of [...plannedSet].sort()) lines.push(`  ${e}`);

const built = [];
const planned = [];
for (const [name] of prodLayers) (isBuilt(name) ? built : planned).push(name);
for (const n of built) lines.push(`  class ${nodeId(n)} built`);
for (const n of planned) lines.push(`  class ${nodeId(n)} planned`);

const builtList = prodLayers.filter(([n]) => isBuilt(n)).map(([n]) => `\`${n}\``);
const plannedList = prodLayers.filter(([n]) => !isBuilt(n)).map(([n]) => `\`${n}\``);

const doc = `# Workspace Dependency Diagram — generated

> GENERATED by \`infra/scripts/generate-dependency-diagram.mjs\` from
> \`docs/dependency-graph.json\` — DO NOT EDIT BY HAND. Drift fails CI
> (structural-gates job). Solid = enforced edge today; dotted = \`plannedEdges\`
> (ADR-025 cumulative wiring: an edge moves from planned to solid in the commit
> that first consumes it). Direction: dependents point at their dependencies.
> Tooling packages (${[...devOnly].map((d) => `\`${d}\``).join(', ')}) are
> dev-only and excluded by design.

\`\`\`mermaid
${lines.join('\n')}
\`\`\`

## Status at generation time

- **Built (${builtList.length}):** ${builtList.join(', ')}
- **Planned (${plannedList.length}):** ${plannedList.join(', ')}

## Layer rules (recap, see docs/Dependency-Audit.md)

1. A package may only import packages listed for it in \`edges\`.
2. No cycles; layers strictly descending (a package depends only on lower layers).
3. Consumers import the package ROOT only; \`adapters|providers|sandbox\` folders
   are private to their own package (vendor-SDK zero-lock-in policy).
`;

if (checkMode) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (current !== doc) {
    console.error(
      'dependency-diagram drift: docs/diagrams/dependencies.md is stale.\n' +
        'Run: node infra/scripts/generate-dependency-diagram.mjs',
    );
    process.exit(1);
  }
  console.log('dependency-diagram check OK');
} else {
  writeFileSync(outPath, doc);
  console.log(`wrote ${outPath} (built=${built.length}, planned=${planned.length})`);
}
